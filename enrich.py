_BOILERPLATE_RE = [re.compile(p, re.MULTILINE) for p in _BOILERPLATE]


# ─────────────────────────────────────────────────────────────
# נרמול טקסט
# ─────────────────────────────────────────────────────────────
def clean_text(raw: str) -> str:
    """מנקה הודעה גולמית לטקסט קריא, בלי לאבד את המשמעות."""
    if not raw:
        return ""
    text = unicodedata.normalize("NFKC", raw)
    text = _INVISIBLE.sub("", text)
    text = _NIQQUD.sub("", text)
    for pattern in _BOILERPLATE_RE:
        text = pattern.sub("", text)
    text = _URL.sub("", text)
    text = _EMOJI.sub(" ", text)
    text = _MULTISPACE.sub(" ", text)
    return text.strip()


def normalize_for_match(text: str) -> str:
    """נרמול אגרסיבי — רק להשוואה, לא לתצוגה.

    גרש/גרשיים בראשי תיבות עבריים מנורמלים לרווח (ת"א → "ת א"),
    לא נמחקים. ASCII (" ') כבר מקבל את זה דרך _PUNCT למטה, כי הוא
    לא נמנה עם טווח האותיות העבריות ולכן לא שורד את הסינון. גרש/
    גרשיים תקניים (׳ ״) כן נמנים עם הטווח הזה ושורדים אותו — בלי
    הטיפול המפורש כאן הם לא הופכים לרווח, ו"צה\"ל" (ASCII) ו"צה״ל"
    (טיפוגרפיה עברית תקנית, נפוצה מאוד במקורות חדשות) מנרמלים לשתי
    מחרוזות שונות. כך חמק דיווח שלם על ה-FBI שהכיל "בארה״ב" בלי שום
    סימן אחר לזיקה לישראל — מילת המפתח "ארה\"ב" לא תפסה אותו.
    """
    text = clean_text(text)
    text = text.replace("״", " ").replace("׳", " ")
    text = _PUNCT.sub(" ", text)
    return _MULTISPACE.sub(" ", text).strip().lower()


# אותיות השימוש: בכל"ם + ו + ש. בעברית הן נדבקות למילה עצמה,
# ולכן "בקריית שמונה" לא מכיל את המחרוזת "קריית שמונה".
# זו הסיבה מספר אחת שחילוץ ישויות בעברית נכשל בשקט.
_PREFIX_LETTERS = "בלמכשווה"


def strip_prefix(token: str) -> str:
    """מסיר אות שימוש מובילה. שמרני — לא נוגע במילים קצרות."""
    if len(token) > 3 and token[0] in "בלמכשו":
        stripped = token[1:]
        if len(stripped) > 2:
            return stripped.removeprefix("ה") if len(stripped) > 3 else stripped
    if len(token) > 3 and token[0] == "ה":
        return token[1:]
    return token


def make_title(text: str, max_len: int = 90) -> str:
    """כותרת מהמשפט הראשון. ערוצי טלגרם לא שולחים כותרות."""
    text = clean_text(text)
    if not text:
        return "דיווח ללא כותרת"
    first = re.split(r"(?<=[.!?])\s|\n", text, maxsplit=1)[0].strip()
    if len(first) > max_len:
        cut = first[:max_len].rsplit(" ", 1)[0]
        return cut + "…"
    return first or text[:max_len]


# ─────────────────────────────────────────────────────────────
# חילוץ מיקום
# ─────────────────────────────────────────────────────────────
def _term_pattern(needle: str) -> re.Pattern:
    """בונה ביטוי שסובל אותיות שימוש בתחילת השם.

    "קריית שמונה" צריך לתפוס גם "בקריית שמונה",
    "העיר העתיקה" גם "בעיר העתיקה" — כאן ה"א הידיעה מתחלפת בב'.
    לכן מפרידים את ה"א מהגרעין ומאפשרים כל צירוף לפניו.
    """
    words = needle.split()
    first = words[0]
    core = first[1:] if first.startswith("ה") and len(first) > 3 else first
    rest = (" " + " ".join(words[1:])) if len(words) > 1 else ""

    if len(core) >= 4 or len(words) > 1:
        head = f"[{_PREFIX_LETTERS}]{{0,2}}ה?{re.escape(core)}"
    else:
        # שמות קצרים ("עזה", "צור") — בלי סבילות לתחיליות.
        # "בעזה" שווה לתפוס, אבל "מעזה" בתוך "מעזהיר" יעלה לנו ביוקר.
        head = re.escape(first)

    return re.compile(r"(?:^|\s)" + head + re.escape(rest) + r"(?=$|\s|,|\.)")


_COMPILED: list[tuple[re.Pattern, str]] = [
    (_term_pattern(normalize_for_match(term)), canonical)
    for term, canonical in _TERMS
    if normalize_for_match(term)
]

# מילים עבריות רגילות שבמקרה מסתיימות בשם מקום אחרי הסרת ה' הידיעה.
# "הגדרה" (מילה במילון) מזוהה כ"ה-גדרה" (העיר) כי _term_pattern מתיר
# ה' אופציונלי גם בלי אף אות שימוש לפניה — בכוונה, כדי לתפוס "העיר
# העתיקה" מול "בעיר העתיקה". המחיר הוא שהצורה החשופה "ה"+גרעין
# מתנגשת עם מילים תמימות. במקום להדק את הביטוי ולפספס מקרים אמיתיים,
# חוסמים כאן את הצורות הספציפיות שכבר נתקלנו בהן.
_FALSE_POSITIVE_FORMS: dict[str, set[str]] = {
    "גדרה": {"הגדרה", "הגדרות"},
}

# מקומות שההתנגשות עם מילה עברית נפוצה כל כך גבוהה שחוסמים כל צורה
# שלהם — גם עם תחילית ("ורימונים", "במודיעין") — ולא רק את הצורה
# החשופה. "איסוף מודיעין"/"רכישת נשק ורימונים" הרבה יותר נפוצים
# בידיעה ביטחונית מאזכור אמיתי של העיר מודיעין או יישוב רימונים.
# בניגוד ל-_FALSE_POSITIVE_FORMS (שמשווה את ההתאמה המדויקת), כאן
# מסירים תחילית לפני ההשוואה — כדי לתפוס גם "ו"/"ל" שמצטרפות למילה.
#
# "סיני" סימטרי באופן שונה: לא רק מקום (חצי האי) אלא גם שם תואר
# נפוץ ("רחפן סיני", "טיל סיני" — כלומר תוצרת סינית). "סעודיה
# העלתה בתימן רחפן סיני... Wing Long 2" קיבל עוגן ישראלי-לכאורה
# (is_foreign_only בודק גם גזטיר) בזכות "סיני" בהוראת "סיני" ולא
# "חצי האי סיני" — כתבה שאין לה שום קשר לישראל עברה כ"רלוונטי".
_ALWAYS_AMBIGUOUS = {"מודיעין", "רימונים", "סיני"}


def extract_location(text: str) -> tuple[str | None, float | None, float | None]:
    """מחזיר (שם מקום, lat, lng) — ההתאמה הארוכה ביותר שנמצאה.

    הסדר קריטי: _TERMS ממוין מהארוך לקצר, כך ש"דרום לבנון" נבדק
    לפני "לבנון" ו"קריית שמונה" לפני "קריית גת".
    """
    if not text:
        return None, None, None
    haystack = normalize_for_match(text)

    for pattern, canonical in _COMPILED:
        match = pattern.search(haystack)
        if not match:
            continue
        matched_text = match.group(0).strip()
        if canonical in _ALWAYS_AMBIGUOUS and matched_text.endswith(canonical) and all(
            c in _PREFIX_LETTERS + "ה" for c in matched_text[:-len(canonical)]
        ):
            continue
        bad_forms = _FALSE_POSITIVE_FORMS.get(canonical)
        if bad_forms and matched_text in bad_forms:
            continue
        lat, lng, _precision = PLACES[canonical]
        return canonical, lat, lng

    return None, None, None


