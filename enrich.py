# הגזירה חלה גם על רשימת העצירה, אחרת "נפגעים" מסונן אבל
# "נפגע" שנוצר ממנו בגזירה נשאר ומזהם את ההשוואה.
_STOPWORD_STEMS: set[str] = set()


# סיומות נטייה נפוצות. בלי הסרתן "אזעקה" ו"אזעקות" הן שתי מילים
# שונות, ושני אתרים שדיווחו על אותו אירוע בלשון יחיד מול רבים
# נראים למדד הדמיון כאירועים שונים. זה מה שהפיל את האיחוד בפועל.
_SUFFIXES = ("יות", "ות", "ים", "יה", "ה", "ת")


def _stem(token: str) -> str:
    """גזירה שמרנית — מסירה סיומת רק אם נשאר גזע בעל ממש."""
    for suffix in _SUFFIXES:
        if token.endswith(suffix) and len(token) - len(suffix) >= 3:
            return token[: -len(suffix)]
    return token


def _significant_tokens(text: str) -> list[str]:
    """מילים נושאות משמעות, בלי אותיות שימוש ובלי סיומות נטייה.

    הסרת התחיליות היא מה שגורם ל"בקריית" ו"קריית" להיחשב אותה מילה,
    והגזירה עושה את אותו דבר ל"אזעקה" מול "אזעקות". בלי שתיהן מדד
    הדמיון נופל בכל פעם ששני מקורות מנסחים אחרת — וזה תמיד המצב.
    """
    global _STOPWORD_STEMS
    if not _STOPWORD_STEMS:
        _STOPWORD_STEMS = {_stem(w) for w in _STOPWORDS} | _STOPWORDS
    tokens = (_stem(strip_prefix(t)) for t in normalize_for_match(text).split())
    return [t for t in tokens if len(t) > 2 and t not in _STOPWORD_STEMS]


def dedup_key(text: str, location: str | None = None,
              when: "datetime | None" = None) -> str:
    """מפתח חסימה — לא טביעת אצבע.

    היסטוריה של שני באגים כאן, ושניהם עלו רק מול נתונים אמיתיים:

    הראשון: המפתח נגזר מכל מילות ההודעה, אז כל הבדל ניסוח שינה
    אותו ושני דיווחים על אותו אירוע לא נפגשו לעולם.

    השני, שהתגלה כשהאתר הראה 0 אירועים מאומתים מתוך 121 דיווחים:
    המפתח כלל דלי זמן. שני אתרים שפרסמו את אותו אירוע בהפרש דקות
    אך משני צדי גבול הדלי קיבלו מפתחות שונים — ומכיוון שהשאילתה
    ממילא מסננת לפי חלון זמן, הדלי רק הזיק. הוסר.

    המפתח עכשיו הוא מקום בלבד (או המילים הבולטות בהיעדר מקום),
    והזמן מטופל היכן שהוא שייך: בתנאי ה-published_at של השאילתה.
    """
    if location:
        seed = f"loc:{location}"
    else:
        tokens = _significant_tokens(text)
        # הארוכות ביותר — קירוב עני ל-IDF, אבל יציב בין ניסוחים
        salient = sorted(sorted(set(tokens), key=len, reverse=True)[:3])
        if not salient:
            return hashlib.sha1((text[:60] or "empty").encode("utf-8")).hexdigest()[:20]
        seed = f"tok:{'|'.join(salient)}"

    return hashlib.sha1(seed.encode("utf-8")).hexdigest()[:20]


def similarity(a: str, b: str) -> float:
    """Jaccard על מילים משמעותיות. 0.0–1.0.

    זה מה שמכריע אם שני דיווחים הם אותו אירוע. מפתח החסימה רק
    מביא את המועמדים; בלי הבדיקה הזו כל שני אירועים באותו יישוב
    באותה שעה היו מתאחדים בטעות.
    """
    set_a, set_b = set(_significant_tokens(a)), set(_significant_tokens(b))
    if not set_a or not set_b:
        return 0.0
    return len(set_a & set_b) / len(set_a | set_b)


def significant_overlap(a: str, b: str, exclude: str = "") -> set[str]:
    """מילים משמעותיות משותפות לשני הטקסטים, מלבד מילות שם המיקום.

    Jaccard גולמי שבור בערוצי טלגרם "מבזקים": שלושה ערוצים על אותה
    פשיטה ביטא ניסחו אותה בסגנון כה שונה שקיבלו 0.116 — נמוך יותר
    משני אירועים שונים באותו יישוב (~0.18-0.22, נמדד ב-test_enrich).
    חפיפה גולמית לא מבדילה ביניהם.

    זה כן מבדיל: שני אירועים שונים באותו יישוב חולקים רק את שם
    היישוב עצמו (חפיפה, אחרי הסרתו, ריקה); אותו אירוע, לעומת זאת,
    תמיד חולק לפחות מילת תוכן משמעותית אחת נוספת — גם בניסוח שונה
    לגמרי — כי שניהם בכל זאת מתארים את אותו הדבר.
    """
    set_a, set_b = set(_significant_tokens(a)), set(_significant_tokens(b))
    exclude_tokens = set(_significant_tokens(exclude))
    return (set_a & set_b) - exclude_tokens


