def screen(item: dict, use_ai: bool = True) -> tuple[bool, str, dict]:
    """מחליט אם הדיווח נכנס לאתר, ומעשיר אותו אם כן.

    use_ai=False מדלג ישר על ה-AI וסופג רק את ההיוריסטיקה — ל-
    backfill (ראה telegram_source.py), שרץ מחדש בכל דיפלוי וסורק
    את היסטוריית כל הערוצים. בלי זה, כל דיפלוי צורך שוב את כל
    מכסת ה-API היומית על תוכן שכבר נסרק בעבר, ומשאיר את התור
    מרוקן בדיוק כשמגיע אירוע אמיתי שדורש שיקול דעת אמיתי.

    מחזיר (לשמור, סיבה, פריט מעודכן).
    """
    text = f"{item.get('title', '')}. {item.get('content', '')}".strip()

    if not is_hebrew(text):
        return False, "לא עברית", item

    # יחס עברית/סה"כ אותיות (is_hebrew) יכול לעבור גם כשיש נתח
    # ערבי משמעותי — "תרגום"/ציטוט מערוץ פלסטיני עם הרבה עברית
    # מסביב. הקו העריכתי: עברית נקייה בלבד, לא "ברובו עברית".
    if has_arabic(text):
        return False, "מכיל ערבית", item

    promoted = matches_promote(text)

    # promote *אינו* עוקף מוחלט. הגרסה הקודמת נתנה לו לגבור על כל
    # חסימה, ועם 79 מילות קידום בטבלה כמעט הכל קודם — דקירה פלילית
    # בבית שמש עברה כי "דקירה" הופיעה באחד מחוקי הקידום.
    #
    # עכשיו: חסימה מוחלטת (ספורט, מזג אוויר, ממומן) גוברת תמיד.
    # בקטגוריות העמומות — פשיעה ותאונות — מה שמכריע הוא הקשר
    # ביטחוני בטקסט עצמו, לא מילה ברשימת קידום. "דקירה" לבדה היא
    # אירוע פלילי; "פיגוע דקירה" או דקירה עם מחבל היא לא.
    blocked = hard_block(text)
    if blocked:
        return False, f"חסום · {blocked}", item

    if is_criminal_context(text):
        return False, "אלימות על רקע פלילי מוצהר", item

    if is_routine_arrest(text):
        return False, "מעצר שגרתי, לא פשיטה דרמטית", item

    if is_stale_arrest_followup(text):
        return False, "מעצר מאוחר של חשודים באירוע ישן, לא אירוע מתפרץ", item

    if is_routine_stone_throw(text):
        return False, "יידוי אבנים שגרתי, בלי נפגעים", item

    if is_unconfirmed_blast(text):
        return False, "פיצוץ שנשמע, לא מאומת ולא מזוהה", item

    if is_petty_nationalist_incident(text):
        return False, "מעשה שנאה/ונדליזם על רקע לאומני, לא איום ביטחוני", item

    if is_own_equipment_malfunction(text):
        return False, "תקלה טכנית בציוד שלנו, לא אירוע ביטחוני", item

    if is_foreign_only(text):
        return False, "חדשות חוץ ללא זיקה לישראל", item

    breaking, why = is_breaking(text)
    if not breaking:
        return False, why, item

    if matches_review(text):
        item["status"] = "reviewing"

    # קידום מ-DB גובר על "אין סימן" חלש, אבל לא על "תקיפה שלנו
    # בחוץ" — אחרת כל ידיעה עם "מחבל"/"תקיפה" (מילות promote גסות)
    # עוקפת את הבדיקה שמבחינה בין תקיפה שלנו לתקיפה עלינו, בדיוק
    # מה שקרה בפועל ("תיעוד מרהיב מעזה... מחבל שהותקף" קודם).
    if promoted and is_outbound_only(text):
        promoted = False

    if promoted:
        item["raw"] = (item.get("raw") or {}) | {"promoted": True}

    if not use_ai or not (GROQ_API_KEY or GEMINI_API_KEY or MISTRAL_API_KEY or ANTHROPIC_API_KEY):
        keep, reason = heuristic_relevance(text)
        if promoted and not keep:
            keep, reason = True, "קודם · חוק promote"
        item["content"] = trim_summary(item.get("content", ""))
        item["raw"] = (item.get("raw") or {}) | {"filter": "heuristic"}
        return keep, reason, item

    verdict = _call_ai(text)
    if verdict is None:
        # ה-API נפל — לא זורקים דיווחים בגלל תקלה זמנית, אבל תמיד
        # דרך ההיוריסטיקה — promote לא מדלג עליה יותר (ראה למעלה).
        keep, reason = heuristic_relevance(text)
        if promoted and not keep:
            keep, reason = True, "קודם · חוק promote"
        item["content"] = trim_summary(item.get("content", ""))
        item["raw"] = (item.get("raw") or {}) | {"filter": "heuristic-fallback"}
        return keep, f"{reason} (AI לא זמין)", item

    ai_summary = verdict.get("summary") or ""
    fabricated = bool(ai_summary) and _has_fabricated_casualties(ai_summary, text)
    if fabricated:
        # ה-AI המציא נפגעים/הרוגים שלא היו בטקסט המקור — לא סומכים
        # על אף חלק מהפסק שלו, כולל relevant, כי ההחלטה עצמה עלולה
        # להתבסס על העובדה המומצאת (ראה dd47c025: "relevant=true" כי
        # ה-AI "האמין" שחיילים נהרגו, כשבפועל זו פעולה שלנו בחוץ).
        # חוזרים להיוריסטיקה הנקייה על הטקסט המקורי, בדיוק כמו כשלון API.
        keep, reason = heuristic_relevance(text)
        if promoted and not keep:
            keep, reason = True, "קודם · חוק promote"
        item["content"] = trim_summary(item.get("content", ""))
        item["raw"] = (item.get("raw") or {}) | {
            "filter": "heuristic-fallback",
            "summary_rejected": "נפגעים שלא במקור",
        }
        if keep:
            item["status"] = "reviewing"
        return keep, f"{reason} (AI המציא נפגעים, נפסל)", item

    if not verdict.get("relevant") and not promoted:
        return False, f"AI · {verdict.get('reason', 'לא רלוונטי')}", item

    summary = trim_summary(ai_summary or item.get("content", ""))
    if summary:
        item["content"] = summary
    if verdict.get("severity") in ("critical", "high", "medium", "low"):
        item["severity"] = verdict["severity"]

    item["raw"] = (item.get("raw") or {}) | {
        "filter": "ai",
        "category": verdict.get("category"),
        "reason": verdict.get("reason"),
        "promoted": promoted or None,
    }
    label = verdict.get("category", "רלוונטי")
    return True, f"AI · {label}" + (" · קודם" if promoted else ""), item
