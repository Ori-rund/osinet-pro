def _has_term(haystack: str, term: str) -> bool:
    """התאמה בטוחה. מילה קצרה חייבת גבול, אחרת היא נבלעת במילה אחרת."""
    needle = normalize_for_match(term)
    if not needle:
        return False
    if len(needle) <= 3:
        return re.search(r"(?:^|\s)" + re.escape(needle) + r"(?=$|\s|,|\.)", haystack) is not None
    return needle in haystack


def is_breaking(text: str) -> tuple[bool, str]:
    """האם זה אירוע שקורה עכשיו, או טקסט על משהו שכבר קרה.

    ברירת המחדל היא כן. רוב הידיעות לא נושאות סמן זמן, ולדרוש
    סמן "חי" מפורש היה זורק את רוב האירועים האמיתיים — "פיגוע
    בצומת, המחבל נוטרל" הוא מתפרץ בלי לומר זאת. לכן חוסמים רק
    על ראיה חיובית לעבר או להצהרה.

    סמן "עכשיו" מפורש גובר על סמן עבר, כדי ש"אזעקות אמש וגם
    עכשיו" לא ייחסם — אבל רק סמן מפורש, לא מילה ביטחונית כללית.
    """
    haystack = normalize_for_match(text)

    if any(_has_term(haystack, k) for k in _LIVE_STRONG):
        return True, "אירוע חי"

    for keyword in _RETROSPECTIVE:
        if _has_term(haystack, keyword):
            return False, f"דיווח על העבר · {keyword}"

    for keyword in _STATEMENT:
        if _has_term(haystack, keyword):
            return False, f"הצהרה או פרשנות · {keyword}"

    return True, "ללא סמן עבר"


def heuristic_relevance(text: str) -> tuple[bool, str]:
    """החלטת רלוונטיות בלי AI. גסה, אבל שומרת על הקו העריכתי.

    "פגיעה בישראל גוברת תמיד" — אבל רק כשהסימן חד-משמעי. סימן חלש
    (_WEAK_IMPACT) לבדו, לצד סימן "פעילות בחוץ", לא באמת אומר שישראל
    נפגעה — "רגע תקיפת מחבלים מעזה" מכיל גם "מחבלים" וגם "מעזה",
    וזו כתבה על צה"ל שתוקף, לא על ישראל שמותקפת.
    """
    haystack = normalize_for_match(text)
    matched = [k for k in _ISRAEL_IMPACT if normalize_for_match(k) in haystack]
    outbound = any(normalize_for_match(k) in haystack for k in _OUTBOUND_STRIKE)
    strong = any(k not in _WEAK_IMPACT for k in matched)

    if strong or (matched and not outbound):
        # פגיעה בישראל גוברת תמיד — גם אם מוזכרת גם תקיפה שלנו
        return True, "סימן פגיעה בישראל"
    if outbound:
        return False, "פעילות בחו״ל בלי פגיעה בישראל"
    return False, "אין סימן לאירוע ביטחוני נוגע לישראל"


def is_outbound_only(text: str) -> bool:
    """True אם הטקסט מתאר פעילות שלנו בחוץ בלי סימן פגיעה בישראל.

    שימוש: וטו על חוקי promote (ראה screen). "תיעוד מרהיב מעזה...
    מחבל שהותקף" מכיל "מחבל" ו"הותקף" — שניהם ברשימת promote
    הגסה ב-DB, שלא מבחינה בין תקיפה שלנו לתקיפה עלינו. הווטו הזה
    הוא בדיוק אותה בדיקה ש-heuristic_relevance כבר עושה, כדי
    שקידום מה-DB לא יעקוף בדיוק את מה שהיא נועדה למנוע.
    """
    return heuristic_relevance(text)[1] == "פעילות בחו״ל בלי פגיעה בישראל"


def trim_summary(text: str, limit: int = SUMMARY_MAX_CHARS) -> str:
    """קיצור לכ-15 שורות בערך בעמוד הדיווח, על גבול משפט."""
    text = (text or "").strip()
    if len(text) <= limit:
        return text
    sentences = re.split(r"(?<=[.!?])\s+", text)
    out = ""
    for sentence in sentences:
        if len(out) + len(sentence) + 1 > limit:
            break
        out = f"{out} {sentence}".strip()
    if out:
        return out
    return text[:limit].rsplit(" ", 1)[0] + "…"


